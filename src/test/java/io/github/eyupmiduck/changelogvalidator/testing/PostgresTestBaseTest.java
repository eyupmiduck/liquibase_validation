package io.github.eyupmiduck.changelogvalidator.testing;

import org.junit.jupiter.api.Test;

import java.sql.Connection;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Exercises {@link PostgresTestBase} against a real PostgreSQL: the shared
 * container, the template database built from the classpath changelog fixture,
 * the per-class cloned database and the shared introspection and SQLSTATE
 * helpers.
 */
class PostgresTestBaseTest extends PostgresTestBase {

    /**
     * The private database is cloned from the migrated template and is usable.
     */
    @Test
    void connectsToAClonedTemplateDatabase() {
        assertTrue(databaseReady(), "the private database should be open");
        String owner = dsl.fetchOne("SELECT current_user::text").get(0, String.class);
        assertEquals(testUser(), owner, "the cloned database connection should use the test role");
    }

    /**
     * A table and column created in the private database are visible to the
     * shared introspection helpers.
     */
    @Test
    void introspectsTablesAndColumns() {
        assertFalse(tableExists("probe_table"), "the table should not exist yet");

        dsl.execute("CREATE TABLE probe_table (id integer NOT NULL, name text)");
        try {
            assertTrue(tableExists("probe_table"), "the table should exist");
            assertTrue(tableExists(PUBLIC_SCHEMA, "probe_table"), "the table should exist in public");
            assertTrue(hasColumn(PUBLIC_SCHEMA, "probe_table", "id"), "the id column should exist");
            assertFalse(hasColumn(PUBLIC_SCHEMA, "probe_table", "missing"), "the missing column should not exist");
            assertEquals("integer", columnAttribute(PUBLIC_SCHEMA, "probe_table", "id", "data_type"));
            assertFalse(triggerExists(PUBLIC_SCHEMA, "probe_table", "no_such_trigger"));
        } finally {
            dsl.execute("DROP TABLE probe_table");
        }
    }

    /**
     * A domain check violation is reported through the shared SQLSTATE
     * helpers, and a second connection opens as the test role.
     */
    @Test
    void assertsSqlStateAndOpensASecondConnection() throws Exception {
        dsl.execute("CREATE DOMAIN probe_positive AS integer CHECK (VALUE > 0)");
        try {
            assertDomainViolation(() -> dsl.fetchValue("SELECT (-1)::probe_positive"));
        } finally {
            dsl.execute("DROP DOMAIN probe_positive");
        }

        try (Connection other = openTestConnection()) {
            assertFalse(other.isClosed(), "the second connection should be usable");
        }
    }

    /**
     * The owner connection can create objects the test role's cloned database
     * sees.
     */
    @Test
    void opensAnOwnerConnection() throws Exception {
        try (Connection owner = openOwnerConnection()) {
            assertFalse(owner.isClosed(), "the owner connection should be usable");
        }
    }

    /**
     * The shared table helpers create a table as the test role and drop it
     * again.
     */
    @Test
    void createsAndDropsATestTable() {
        assertFalse(tableExists("probe_owned"), "the table should not exist yet");
        createTestTable("probe_owned", "id integer");
        try {
            assertTrue(tableExists("probe_owned"), "the table should exist");
        } finally {
            dropTestTable("probe_owned");
        }
        assertFalse(tableExists("probe_owned"), "the table should be dropped");
    }

    /**
     * The column and constraint helpers read identity, storage, compression,
     * generated, nullability, default and validation attributes.
     */
    @Test
    void introspectsColumnAndConstraintAttributes() {
        createTestTable("probe_columns",
                "id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL, "
                        + "name text DEFAULT 'x', amount integer, "
                        + "doubled integer GENERATED ALWAYS AS (amount * 2) STORED, "
                        + "CONSTRAINT probe_id_check CHECK (id > 0)");
        try {
            dsl.execute("ALTER TABLE probe_columns"
                    + " ADD CONSTRAINT probe_amount_check CHECK (amount >= 0) NOT VALID");

            assertEquals("d", columnIdentity(PUBLIC_SCHEMA, "probe_columns", "id"));
            assertFalse(isGenerated(PUBLIC_SCHEMA, "probe_columns", "id"));
            assertEquals("plain", columnStorage(PUBLIC_SCHEMA, "probe_columns", "id"));
            assertEquals("default", columnCompression(PUBLIC_SCHEMA, "probe_columns", "name"));
            assertTrue(isGenerated(PUBLIC_SCHEMA, "probe_columns", "doubled"));

            assertNotNullable(PUBLIC_SCHEMA, "probe_columns", "id");
            assertNullable(PUBLIC_SCHEMA, "probe_columns", "name");
            assertColumnDefault(PUBLIC_SCHEMA, "probe_columns", "name", "'x'");
            assertNoColumnDefault(PUBLIC_SCHEMA, "probe_columns", "amount");

            assertTrue(constraintExists(PUBLIC_SCHEMA, "probe_columns", "probe_id_check"));
            assertTrue(constraintExists(PUBLIC_SCHEMA, "probe_id_check"));
            assertEquals("c", constraintType(PUBLIC_SCHEMA, "probe_id_check"));
            assertValidated(PUBLIC_SCHEMA, "probe_columns", "probe_id_check");
            assertNotValidated(PUBLIC_SCHEMA, "probe_columns", "probe_amount_check");
        } finally {
            dropTestTable("probe_columns");
        }
    }

    /**
     * A call blocked by another session's ACCESS SHARE lock gives up with
     * {@code lock_timeout}'s SQLSTATE through the shared lock helpers.
     */
    @Test
    void givesUpWhileAnotherSessionHoldsAnAccessShareLock() throws Exception {
        createTestTable("probe_lock", "id integer");
        dsl.execute("SET lock_timeout = '100ms'");
        try {
            assertGivesUpWhileTableLocked("probe_lock", 5_000, () ->
                    dsl.execute("ALTER TABLE probe_lock ADD COLUMN blocked integer"));
        } finally {
            dsl.execute("SET lock_timeout = DEFAULT");
            dropTestTable("probe_lock");
        }
    }

    /**
     * A call blocked by another session's lock completes once that session
     * releases it through the shared {@code runWhileTableLocked} helper.
     */
    @Test
    void runsUntilAnotherSessionReleasesItsTableLock() {
        createTestTable("probe_run_lock", "id integer");
        try {
            runWhileTableLocked("probe_run_lock", 300, () ->
                    dsl.execute("ALTER TABLE probe_run_lock ADD COLUMN added integer"));

            assertTrue(hasColumn(PUBLIC_SCHEMA, "probe_run_lock", "added"));
        } finally {
            dropTestTable("probe_run_lock");
        }
    }
}
